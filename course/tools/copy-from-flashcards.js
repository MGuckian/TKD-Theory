// Copies the flashcard deck and answer-checking code from ../../index.html into the course,
// so the course runs as a separate page with no link to the flashcard app.
// Run with: node course/tools/copy-from-flashcards.js   (re-run if the flashcard deck changes)
var fs = require("fs"), path = require("path");
var root = path.join(__dirname, "..", "..");
var html = fs.readFileSync(path.join(root, "index.html"), "utf8");
function slice(startMarker, endMarker){
  var s = html.indexOf(startMarker), e = html.indexOf(endMarker, s);
  if(s < 0 || e < 0) throw new Error("marker not found: " + startMarker);
  return html.slice(s, e);
}
var head = "// GENERATED by course/tools/copy-from-flashcards.js from index.html. Do not edit by hand.\n";
var deck = slice("var TOPICS = {", "var LEVEL_BANDS");
fs.writeFileSync(path.join(root, "course", "deck.js"), head + deck.trim() + "\n");
var lib = "var BOX_INTERVALS = " + /var BOX_INTERVALS = (\[[^\]]*\]);/.exec(html)[1] + ";\n" +
  slice("var todayISO", "var BOX_INTERVALS") +
  slice("function normalize(s){", "function defaultState(){");
fs.writeFileSync(path.join(root, "course", "lib.js"), head + lib.trim() + "\n");
console.log("deck.js and lib.js written");
